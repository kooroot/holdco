/**
 * Locate the Codex CLI the SDK would run, so the kernel can put a wrapper in front of it.
 *
 * Why a wrapper: Codex skips non-managed hooks until a person has reviewed and trusted them
 * (`/hooks`), and the SDK has no option for the global `--dangerously-bypass-hook-trust` flag.
 * The hook Holdco registers lives in a kernel-generated, agent-unreadable CODEX_HOME, so the kernel
 * has already vetted it; the wrapper passes the flag before `exec`. Plugins are disabled and no
 * project is trusted in that home, so no other hook source is loaded.
 *
 * Resolution mirrors `findCodexPath` in @openai/codex-sdk 0.164.0 (not exported).
 */
import { existsSync, statSync } from "node:fs"
import { createRequire } from "node:module"
import { dirname, join } from "node:path"
import { fileURLToPath } from "node:url"

const TRIPLES: Record<string, string> = {
  "linux-x64": "x86_64-unknown-linux-musl",
  "linux-arm64": "aarch64-unknown-linux-musl",
  "android-x64": "x86_64-unknown-linux-musl",
  "android-arm64": "aarch64-unknown-linux-musl",
  "darwin-x64": "x86_64-apple-darwin",
  "darwin-arm64": "aarch64-apple-darwin",
  "win32-x64": "x86_64-pc-windows-msvc",
  "win32-arm64": "aarch64-pc-windows-msvc",
}
const PLATFORM_PACKAGES: Record<string, string> = {
  "x86_64-unknown-linux-musl": "@openai/codex-linux-x64",
  "aarch64-unknown-linux-musl": "@openai/codex-linux-arm64",
  "x86_64-apple-darwin": "@openai/codex-darwin-x64",
  "aarch64-apple-darwin": "@openai/codex-darwin-arm64",
  "x86_64-pc-windows-msvc": "@openai/codex-win32-x64",
  "aarch64-pc-windows-msvc": "@openai/codex-win32-arm64",
}

export interface CodexBinary {
  readonly path: string
  /** Directories the SDK prepends to PATH (bundled ripgrep and helpers). */
  readonly pathDirs: ReadonlyArray<string>
}

const isFile = (p: string) => existsSync(p) && statSync(p).isFile()
const isDir = (p: string) => existsSync(p) && statSync(p).isDirectory()

export const resolveCodexBinary = (): CodexBinary => {
  const triple = TRIPLES[`${process.platform}-${process.arch}`]
  const platformPackage = triple === undefined ? undefined : PLATFORM_PACKAGES[triple]
  if (triple === undefined || platformPackage === undefined) throw new Error(`Codex: unsupported platform ${process.platform}-${process.arch}`)
  // The SDK is ESM-only, so resolve it with import semantics, then follow its own dependency.
  const sdk = createRequire(fileURLToPath(import.meta.resolve("@openai/codex-sdk")))
  const cli = createRequire(sdk.resolve("@openai/codex/package.json"))
  const root = join(dirname(cli.resolve(`${platformPackage}/package.json`)), "vendor", triple)
  const exe = process.platform === "win32" ? "codex.exe" : "codex"
  const current = join(root, "bin", exe)
  if (isFile(current) && isFile(join(root, "codex-package.json"))) {
    return { path: current, pathDirs: [join(root, "codex-path")].filter(isDir) }
  }
  const legacy = join(root, "codex", exe)
  if (isFile(legacy)) return { path: legacy, pathDirs: [join(root, "path")].filter(isDir) }
  throw new Error(`Codex: CLI binary not found under ${root}; install @openai/codex with optional dependencies`)
}

const shQuote = (s: string) => `'${s.replace(/'/g, `'\\''`)}'`

/** POSIX wrapper that adds the hook-trust bypass as a global flag, before the SDK's `exec`. */
export const wrapperScript = (binary: string): string =>
  `#!/bin/sh\n# Generated by holdco. The only hook this CODEX_HOME registers is the kernel's guard.\nexec ${shQuote(binary)} --dangerously-bypass-hook-trust "$@"\n`
