/**
 * SessionSpec → Codex SDK options plus a per-session CODEX_HOME. Pure; typechecked against @openai/codex-sdk.
 *
 * Codex has no system-prompt option, no per-tool allowlist and no in-process hooks, so:
 *   • company instructions are prepended to the first input;
 *   • the sandbox is a permission profile written into a kernel-owned CODEX_HOME;
 *   • the kernel's compiled guard is registered there as a PreToolUse command hook;
 *   • nothing is read from the user's ~/.codex or from the project's .codex/.
 *
 * Verified against the Codex CLI 0.164.0 binary (risk R8, docs/design/05-security.md):
 *   • `--strict-config` accepts every key written here; `codex doctor` reports the profile active.
 *   • `codex sandbox` under this home: denied paths are unreadable, writes outside the
 *     workspace fail, writes inside succeed (see test/codex.live.test.ts, and `holdco doctor`).
 *   • Permission profiles are ignored as soon as `sandbox_mode` is set anywhere, including the
 *     SDK's `sandboxMode` (it passes `--sandbox`). So neither is ever set.
 *   • Filesystem access values are `read`, `write`, `deny`.
 * Hooks are not verified live (they need a model turn); docs say they also cover apply_patch and
 * MCP tools but are not a complete boundary. The profile is the boundary; the hook adds interrupts.
 */
import { existsSync, readFileSync } from "node:fs"
import type { CodexOptions, ThreadOptions, TurnOptions } from "@openai/codex-sdk"
import type { Capability, SessionSpec } from "@holdco/kernel/engine"
import { type CodexBinary, wrapperScript } from "./binary.ts"
import { type TomlTable, type TomlValue, toToml } from "./toml.ts"

export interface CodexPlan {
  readonly codex: CodexOptions
  readonly thread: ThreadOptions
  readonly turn: Omit<TurnOptions, "signal">
  readonly input: string
  /** Files to write into `home` before starting, with their modes. */
  readonly files: Readonly<Record<string, { readonly body: string; readonly mode: number }>>
  readonly home: string
}

/** Features that would let a session act outside the kernel's view, or delegate on its own. */
export const DISABLED_FEATURES = [
  "multi_agent",
  "plugins",
  "remote_plugin",
  "apps",
  "browser_use",
  "browser_use_external",
  "browser_use_full_cdp_access",
  "computer_use",
  "in_app_browser",
  "in_app_local_automation",
  "image_generation",
  "skill_mcp_dependency_install",
  "workspace_dependencies",
] as const

export type Access = "read" | "write"
export const workspaceAccess = (caps: ReadonlyArray<Capability>): Access =>
  caps.includes("write") || caps.includes("shell") ? "write" : "read"

export const codexConfig = (spec: SessionSpec): TomlTable => {
  const access = workspaceAccess(spec.role.capabilities)
  const filesystem: Record<string, TomlValue> = { ":root": "read" }
  if (access === "write") {
    filesystem[":tmpdir"] = "write"
    filesystem[":slash_tmp"] = "write"
    for (const r of spec.sandbox.writableRoots) if (r !== spec.cwd) filesystem[r] = "write"
  }
  for (const p of spec.sandbox.denyWrite) filesystem[p] = "read"
  for (const p of spec.sandbox.denyRead) filesystem[p] = "deny"
  filesystem[":workspace_roots"] = { ".": access }

  const domains = spec.sandbox.allowedDomains
  const network: Record<string, TomlValue> = { enabled: domains.length > 0 }
  if (domains.length > 0) network["domains"] = Object.fromEntries(domains.map((d) => [d, "allow"]))

  const company: TomlTable =
    spec.tools.kind === "http"
      ? { url: spec.tools.url, bearer_token_env_var: "HOLDCO_SESSION_TOKEN" }
      : { command: spec.tools.command, args: [...spec.tools.args], env: { HOLDCO_SESSION_TOKEN: spec.tools.token } }

  const features: Record<string, TomlValue> = { hooks: true }
  for (const f of DISABLED_FEATURES) features[f] = false
  // Domain rules are enforced only through Codex's proxy; without it, enabled network is unfiltered.
  if (domains.length > 0) features["network_proxy"] = true

  return {
    approval_policy: "never",
    cli_auth_credentials_store: "file",
    default_permissions: "holdco",
    // Project AGENTS.md is supplied by the kernel from the default branch, never read from the worktree.
    project_doc_max_bytes: 0,
    permissions: { holdco: { description: `holdco session ${spec.sessionId}`, filesystem, network } },
    shell_environment_policy: { inherit: "core", exclude: ["*KEY*", "*TOKEN*", "*SECRET*"] },
    mcp_servers: { company },
    features,
  }
}

export const codexHooks = (spec: SessionSpec) => ({
  hooks: { PreToolUse: [{ matcher: "*", hooks: [{ type: "command", command: spec.hookCommand }] }] },
})

export const codexHome = (spec: SessionSpec, binary: CodexBinary): CodexPlan["files"] => ({
  "config.toml": { body: `# Generated by holdco for session ${spec.sessionId}. Do not edit.\n${toToml(codexConfig(spec))}\n`, mode: 0o600 },
  "hooks.json": { body: `${JSON.stringify(codexHooks(spec), null, 2)}\n`, mode: 0o600 },
  "bin/codex": { body: wrapperScript(binary.path), mode: 0o700 },
  // Subscription login: the Operator's cached credentials, private to this home (agents cannot read .holdco/)
  ...(spec.auth.mode === "subscription" && spec.auth.credentialsFile !== undefined && existsSync(spec.auth.credentialsFile)
    ? { "auth.json": { body: readFileSync(spec.auth.credentialsFile, "utf8"), mode: 0o600 } }
    : {}),
})

/**
 * OpenAI structured outputs accept only "strict" schemas: every object lists its properties, all
 * required, `additionalProperties: false`. A map (`additionalProperties: <schema>`, as in a
 * Verdict's `scores`) cannot be expressed, and the API rejects the request — which ended Codex
 * judge sessions with exit 1 on the first live run. Such schemas go into the prompt instead and
 * the final message is parsed (the kernel validates and retries once).
 */
export const strictCompatible = (schema: unknown): boolean => {
  if (Array.isArray(schema)) return schema.every(strictCompatible)
  if (schema === null || typeof schema !== "object") return true
  const o = schema as Record<string, unknown>
  if (o["type"] === "object") {
    const ap = o["additionalProperties"]
    if (ap !== undefined && ap !== false) return false
    const props = (o["properties"] ?? {}) as Record<string, unknown>
    const req = (o["required"] ?? []) as Array<string>
    if (Object.keys(props).some((k) => !req.includes(k))) return false
  }
  return Object.values(o).every(strictCompatible)
}

export const toCodexOptions = (spec: SessionSpec, binary: CodexBinary): CodexPlan => {
  const home = `${spec.stateDir}/codex-home`
  const caps = spec.role.capabilities
  // No sandboxMode, no networkAccessEnabled: either would bring back the legacy sandbox and
  // silently drop the permission profile.
  const thread: ThreadOptions = {
    model: spec.assignment.model,
    workingDirectory: spec.cwd,
    approvalPolicy: "never",
    webSearchMode: caps.includes("web") ? "live" : "disabled",
    skipGitRepoCheck: false,
  }
  if (spec.assignment.effort !== undefined) thread.modelReasoningEffort = spec.assignment.effort
  const path = [...binary.pathDirs, spec.env["PATH"] ?? ""].filter((p) => p !== "").join(":")
  // The command hook is a child of the codex process and reads these to judge paths and identity
  // (packages/kernel/src/hook.ts); without them it would treat the worktree as the company root.
  const env: Record<string, string> = {
    ...spec.env,
    PATH: path,
    CODEX_HOME: home,
    HOLDCO_SESSION_TOKEN: spec.tools.token,
    HOLDCO_COMPANY_ROOT: spec.companyRoot,
    AGENT_ID: spec.role.role,
    AGENT_DEPT: spec.role.department,
    ...(spec.projectRoot ? { HOLDCO_PROJECT_ROOT: spec.projectRoot, HOLDCO_PROJECT_LOCKED: JSON.stringify(spec.projectLocked ?? []) } : {}),
  }
  const authKey = spec.auth.mode === "api_key" ? Object.keys(spec.env).find((k) => /API_KEY$/.test(k)) : undefined
  const codex: CodexOptions = {
    codexPathOverride: `${home}/bin/codex`,
    env,
    ...(authKey ? { apiKey: spec.env[authKey] as string } : {}),
  }
  const strict = spec.outputSchema !== undefined && strictCompatible(spec.outputSchema)
  const schemaInPrompt = spec.outputSchema !== undefined && !strict
    ? `\n\n---\n\nYour final message must be exactly one JSON object matching this JSON Schema and nothing else (no prose, no code fence):\n${JSON.stringify(spec.outputSchema)}`
    : ""
  return {
    codex,
    thread,
    turn: strict ? { outputSchema: spec.outputSchema } : {},
    input: `${spec.instructions}\n\n---\n\n${spec.prompt}${schemaInPrompt}`,
    files: codexHome(spec, binary),
    home,
  }
}
