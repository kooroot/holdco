/**
 * For every guarantee an engine does not give natively, the kernel names what it does instead.
 * Used by `holdco doctor` (to explain), by the supervisor (to switch compensations on), and by
 * tests (so that adding an engine with a new gap fails loudly until a compensation exists).
 */
import type { EngineCapabilities } from "./types.ts"

export interface Compensation {
  readonly gap: string
  readonly kernelDoes: string
  /** `prevent`: the risk is closed. `detect`: caught and reverted after the fact. */
  readonly strength: "prevent" | "detect"
}

export const compensations = (caps: EngineCapabilities): Array<Compensation> => {
  const out: Array<Compensation> = []
  if (!caps.abort) {
    out.push({ gap: "no abort", kernelDoes: "kill the engine process on timeout or interrupt", strength: "prevent" })
  }
  if (!caps.systemInstructions) {
    out.push({
      gap: "no system instructions",
      kernelDoes: "prepend company instructions to the first input; the guard and sandbox do not depend on the model obeying them",
      strength: "prevent",
    })
  }
  if (!caps.structuredOutput) {
    out.push({ gap: "no structured output", kernelDoes: "parse the final text and validate it with Effect Schema; one retry, then reject", strength: "detect" })
  }
  if (!caps.reportsCost) {
    out.push({ gap: "no cost reporting", kernelDoes: "meter spend from token usage and engines.codex.prices", strength: "prevent" })
  }
  if (!caps.midSessionBudgetCap) {
    out.push({
      gap: "no mid-session budget cap",
      kernelDoes: "reserve the session cap from the share before dispatch; the adapter aborts past maxTurns completed actions or the session timeout; spend is metered when the engine reports usage and reconciled",
      strength: "detect",
    })
  }
  if (caps.preToolHook === "none") {
    out.push({
      gap: "no pre-tool hook",
      kernelDoes: "watch file-change and command events, abort on a locked path and revert the worktree; diff gate makes any such merge T3",
      strength: "detect",
    })
  }
  if (caps.preToolHook === "command") {
    out.push({
      gap: "hook runs as a command, not in-process",
      kernelDoes:
        "register the compiled guard binary in the session's kernel-owned engine home and start the engine through a wrapper that waives hook trust for that home only (plugins off, no project trusted); the OS sandbox stays the boundary",
      strength: "prevent",
    })
  }
  if (!caps.subagentIdentityInHooks) {
    out.push({ gap: "no subagent identity in hooks", kernelDoes: "juniors run as separate kernel sessions via delegate_start, never as engine subagents", strength: "prevent" })
  }
  if (!caps.osSandboxWrites) {
    out.push({ gap: "no OS write sandbox", kernelDoes: "refuse to run roles with write or shell capability on this engine", strength: "prevent" })
  }
  if (caps.osSandboxDenyRead === "profile") {
    out.push({
      gap: "read denial depends on an engine permission profile",
      kernelDoes: "write the profile into a kernel-owned engine home, never set the legacy sandbox options that would override it, and have doctor probe on this host that a denied path is really unreadable",
      strength: "prevent",
    })
  }
  if (caps.osSandboxDenyRead === "none") {
    out.push({ gap: "no read denial", kernelDoes: "refuse to place the session where state or canaries are reachable; require a separate OS user", strength: "prevent" })
  }
  if (caps.projectConfigIsolation === "engine-home") {
    out.push({
      gap: "engine reads user and project config by default",
      kernelDoes: "point the engine at a per-session home generated by the kernel; project config files are locked",
      strength: "prevent",
    })
  }
  if (caps.projectConfigIsolation === "none") {
    out.push({ gap: "project config is loaded", kernelDoes: "lock project settings, hooks and MCP files and reject merges that touch them (T3)", strength: "detect" })
  }
  return out
}
