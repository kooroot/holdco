/**
 * Create a company repository: base template + enabled modules + company.yaml, then git init
 * and tag `r0` so sessions always have a release to be built from (docs/design D23, D26).
 * Hook build, dependency install and service installation are separate steps of `holdco init`.
 */
import { spawnSync } from "node:child_process"
import { cpSync, existsSync, mkdirSync, readdirSync, readFileSync, writeFileSync } from "node:fs"
import * as NodePath from "node:path"
import type { CompanyConfig } from "../config/company.ts"
import { assemble } from "./assemble.ts"
import { loadPreset, moduleDir, TemplateError } from "./templates.ts"

export interface ScaffoldOptions {
  readonly dir: string
  readonly preset: string
  /** Operator's GitHub handle for CODEOWNERS and company.yaml. */
  readonly github?: string
  readonly companyName?: string
  readonly mission?: string
  readonly timezone?: string
  readonly language?: "en" | "ko"
  /** First project: path to its git repository (absolute or relative to `dir`). */
  readonly projectPath?: string
  readonly projectId?: string
  /** Where the service will run; the wizard picks it from the platform. */
  readonly host?: "linux-systemd" | "macos-launchd"
  /** `false` skips git init / commit / tag (tests without git). */
  readonly git?: boolean
  readonly kernelVersion: string
  /**
   * The `packages/` directory of a Holdco checkout. When set, the company depends on the kernel and
   * engines through `bun link` (`link:@holdco/<pkg>`) instead of the npm registry — the way to run
   * from source before a release. The caller registers the links (`bun link` in each package).
   */
  readonly packagesDir?: string
}

export interface ScaffoldResult {
  readonly dir: string
  readonly modules: ReadonlyArray<string>
  readonly config: CompanyConfig
  readonly tagged: boolean
}

const KERNEL_PACKAGE = "@holdco/kernel"
const ENGINE_PACKAGE = { claude: "@holdco/engine-claude", codex: "@holdco/engine-codex" } as const

const copyTemplate = (from: string, to: string) =>
  cpSync(from, to, {
    recursive: true,
    filter: (src) => NodePath.basename(src) !== "module.yaml" || NodePath.dirname(src) !== from,
  })

export const renderCompanyYaml = (config: CompanyConfig, preset: string): string =>
  [
    "# yaml-language-server: $schema=node_modules/@holdco/kernel/schema/company.schema.json",
    `# Generated by \`holdco init --preset ${preset}\`. Owned by the Operator; locked for every agent.`,
    "# Check edits with `holdco config check company.yaml`.",
    "",
    Bun.YAML.stringify(config, null, 2),
  ].join("\n")

/** governance/strategy.md rendered from company.yaml, so the CEO's first cycle has something to allocate against. */
export const renderStrategy = (config: CompanyConfig): string => {
  const period = new Date().toISOString().slice(0, 7)
  const rows = config.projects.map((p) => `| ${p.id} | ${p.class} | ${Math.round(p.share * 100)}% | ${p.kill_criteria ?? (p.class === "core" ? "the main bet" : "")} |`)
  return [
    "# Strategy Document",
    "",
    "> 🔒 **Locked.** Operator only. The CEO allocates capacity against this file and nothing else; every ticket it opens must serve an objective below.",
    "> 🔒 **잠금.** 운영자만 수정합니다. CEO는 오직 이 파일을 기준으로 용량을 배분하고, 여는 모든 티켓은 아래 목표 중 하나를 위한 것이어야 합니다.",
    "",
    `# Strategy — ${period}`,
    "",
    "## Mission",
    config.company.mission,
    "",
    "## Objectives this period (max 3)",
    "<!-- Operator: replace the example row. The CEO opens no tickets while this table only holds the example. -->",
    "| # | Objective | Measurable target | Why it matters |",
    "|---|---|---|---|",
    "| 1 | (example) Ship the first usable version | a user completes the main flow without help | nothing else matters before this |",
    "",
    "## Portfolio",
    "Project ids are `company.yaml:projects[].id`; register projects with `holdco project add <path>`.",
    "| Project | Class | Capacity share | Notes |",
    "|---|---|---|---|",
    ...(rows.length ? rows : ["| (none registered) | | | run `holdco project add ../your-repo` |"]),
    "",
    "Classes: core (most capacity), experiment (capped, has kill criteria), maintenance (bugs, security, docs only), brand (content and community).",
    "",
    "## Kill criteria for experiments",
    "| Project | Stop if | Review date |",
    "|---|---|---|",
    ...config.projects.filter((p) => p.class === "experiment").map((p) => `| ${p.id} | ${p.kill_criteria ?? ""} | |`),
    "",
    "## Non-goals",
    "- (Operator: things the company must not spend capacity on this period)",
    "",
    "## Constraints",
    `- Monthly budget: $${config.budget.monthly_usd}; per session: $${config.budget.session_max_usd} (company.yaml:budget)`,
    "",
    "## 한국어",
    "미션, 이번 기간 목표(최대 3개, 측정 가능한 목표치), 포트폴리오(프로젝트 등급과 용량 비율), 실험 중단 기준, 하지 않을 것, 제약을 위 표에 채웁니다. 목표 표가 예시 한 줄뿐이면 CEO는 티켓을 열지 않습니다.",
    "",
  ].join("\n")
}

const git = (dir: string, ...args: Array<string>) =>
  spawnSync("git", args, {
    cwd: dir,
    encoding: "utf8",
    env: {
      ...process.env,
      GIT_AUTHOR_NAME: process.env["GIT_AUTHOR_NAME"] ?? "holdco",
      GIT_AUTHOR_EMAIL: process.env["GIT_AUTHOR_EMAIL"] ?? "holdco@localhost",
      GIT_COMMITTER_NAME: process.env["GIT_COMMITTER_NAME"] ?? "holdco",
      GIT_COMMITTER_EMAIL: process.env["GIT_COMMITTER_EMAIL"] ?? "holdco@localhost",
    },
  })

export const scaffold = (opts: ScaffoldOptions): ScaffoldResult => {
  if (existsSync(opts.dir) && readdirSync(opts.dir).length > 0) {
    throw new TemplateError(`${opts.dir} is not empty`)
  }
  const preset = loadPreset(opts.preset)
  const projectRel = opts.projectPath === undefined ? undefined : NodePath.relative(opts.dir, NodePath.resolve(opts.projectPath))
  const projectId = opts.projectId ?? (opts.projectPath === undefined ? undefined : NodePath.basename(NodePath.resolve(opts.projectPath)).toLowerCase().replace(/[^a-z0-9-]/g, "-"))
  const named = {
    ...preset,
    company: { ...preset.company, name: opts.companyName ?? preset.company.name, mission: opts.mission ?? preset.company.mission, timezone: opts.timezone ?? preset.company.timezone, ...(opts.language ? { language: opts.language } : {}) },
    operator: { ...preset.operator, github: opts.github ?? preset.operator.github },
    ...(opts.host ? { runtime: { ...preset.runtime, host: opts.host } } : {}),
    ...(projectRel !== undefined && projectId !== undefined
      ? { projects: [{ id: projectId, path: projectRel, class: "core" as const, share: 1, locked: ["AGENTS.md", "CLAUDE.md", ".github/**"] }] }
      : {}),
  }
  const assembled = assemble(named)
  if (!assembled.ok) throw new TemplateError(assembled.errors.join("\n"))
  const { config, modules } = assembled

  mkdirSync(opts.dir, { recursive: true })
  for (const id of modules) copyTemplate(moduleDir(id), opts.dir)

  writeFileSync(NodePath.join(opts.dir, "company.yaml"), renderCompanyYaml(config, opts.preset))
  writeFileSync(NodePath.join(opts.dir, "governance", "strategy.md"), renderStrategy(config))

  const owners = NodePath.join(opts.dir, ".github", "CODEOWNERS")
  if (opts.github) writeFileSync(owners, readFileSync(owners, "utf8").replaceAll("@OPERATOR", `@${opts.github.replace(/^@/, "")}`))

  // From a checkout: `link:<name>` resolves the global links `bun link` registered in each package
  // (create-holdco does that); a path-based link: or file: does not survive the packages' workspace deps.
  const spec = (pkg: string) => (opts.packagesDir ? `link:${pkg}` : opts.kernelVersion)
  const dependencies: Record<string, string> = { [KERNEL_PACKAGE]: spec(KERNEL_PACKAGE) }
  for (const id of Object.keys(config.engines) as Array<keyof typeof ENGINE_PACKAGE>) {
    dependencies[ENGINE_PACKAGE[id]] = spec(ENGINE_PACKAGE[id])
  }
  writeFileSync(
    NodePath.join(opts.dir, "package.json"),
    `${JSON.stringify(
      {
        name: config.company.name,
        private: true,
        type: "module",
        scripts: { doctor: "holdco doctor", supervise: "holdco supervise", "build-hook": "holdco build-hook" },
        dependencies,
      },
      null,
      2,
    )}\n`,
  )

  let tagged = false
  if (opts.git !== false) {
    const steps: Array<Array<string>> = [
      ["init", "-q", "-b", "main"],
      ["add", "-A"],
      ["commit", "-q", "-m", `holdco: create ${config.company.name} from preset ${opts.preset}`],
      ["tag", "r0"],
    ]
    for (const step of steps) {
      const r = git(opts.dir, ...step)
      if (r.status !== 0) throw new TemplateError(`git ${step[0]} failed: ${r.stderr}`)
    }
    tagged = true
  }
  return { dir: opts.dir, modules, config, tagged }
}
